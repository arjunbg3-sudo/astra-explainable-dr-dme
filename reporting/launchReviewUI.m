%% LOAD IMAGE

    function loadImage(~,~)

        [file,path] = uigetfile( ...
            {"*.png;*.jpg;*.jpeg;*.tif;*.tiff", ...
             "Fundus Images (*.png, *.jpg, *.jpeg, *.tif, *.tiff)"}, ...
             "Select Fundus Image");

        if isequal(file,0)
            return;
        end

        currentImagePath = fullfile(path,file);

        currentImage = imread(currentImagePath);

        if ndims(currentImage) == 2
            currentImage = repmat(currentImage,[1 1 3]);
        end

        if size(currentImage,3) > 3
            currentImage = currentImage(:,:,1:3);
        end

        imshow(currentImage,"Parent",axOriginal);

        cla(axGradCAM);
        axis(axGradCAM,"off");

        qualityLabel.Text = "Image Quality: Loaded";
        gradeLabel.Text = "DR Grade: --";
        diagnosisLabel.Text = "Diagnosis: --";
        referableLabel.Text = "Referable: --";
        confidenceLabel.Text = "Model Confidence: --";

        statusLabel.Text = ...
            "Image loaded. Click Analyze Image.";

        reviewLabel.Text = "Review status: Pending";

        reviewStatus = "Pending";
        currentResult = struct();

    end

%% ANALYZE IMAGE

    function analyzeImage(~,~)

        if isempty(currentImagePath)

            uialert(fig, ...
                "Please load a fundus image first.", ...
                "NetraScreen");

            return;

        end

        statusLabel.Text = ...
            "Running NetraScreen analysis...";

        drawnow;

        try

            % Use the SAME working pipeline that we verified
            imdsOne = imageDatastore( ...
                {char(currentImagePath)});

            augOne = augmentedImageDatastore( ...
                inputSize, ...
                imdsOne);

            scores = minibatchpredict(net,augOne);

            [predictedLabel,confidence] = ...
                scores2label(scores,classNames);

            predictedIdx = ...
                find(classNames == predictedLabel) - 1;

            diagnosis = ...
                diagnoses(predictedIdx + 1);

            referable = ...
                predictedIdx >= 2;

            % Update results

            qualityLabel.Text = ...
                "Image Quality: Gradable";

            gradeLabel.Text = sprintf( ...
                "DR Grade: %d / 4",predictedIdx);

            diagnosisLabel.Text = ...
                "Diagnosis: " + diagnosis;

            if referable

                referableLabel.Text = ...
                    "Referable: YES";

                referableLabel.FontColor = ...
                    [0.95 0.55 0.25];

            else

                referableLabel.Text = ...
                    "Referable: NO";

                referableLabel.FontColor = ...
                    [0.30 0.85 0.50];

            end

            confidenceLabel.Text = sprintf( ...
                "Model Confidence: %.2f%%", ...
                confidence*100);

            statusLabel.Text = ...
                "Analysis complete. Human review recommended.";

            % Store classification

            currentResult.imagePath = currentImagePath;
            currentResult.drGrade = predictedIdx;
            currentResult.diagnosis = diagnosis;
            currentResult.referable = referable;
            currentResult.confidence = confidence;

            % Grad-CAM

            try

                [scoreMap,overlay] = ...
                    makeGradCAM( ...
                        net, ...
                        currentImage, ...
                        predictedIdx);

                imshow(overlay,"Parent",axGradCAM);

                title(axGradCAM, ...
                    sprintf("Predicted Grade %d",predictedIdx), ...
                    "Color",[0.8 0.9 1], ...
                    "FontSize",11);

                currentResult.gradCAM = scoreMap;
                currentResult.gradCAMOverlay = overlay;

            catch camError

                warning( ...
                    "NetraScreen Grad-CAM warning: %s", ...
                    camError.message);

                currentResult.gradCAM = [];
                currentResult.gradCAMOverlay = [];

            end

            reviewStatus = "Pending";

            reviewLabel.Text = ...
                "Review status: Pending";

            drawnow;

        catch ME

            statusLabel.Text = ...
                "Analysis failed.";

            uialert(fig, ...
                getReport(ME,"basic","hyperlinks","off"), ...
                "NetraScreen Analysis Error");

        end

    end

%% ACCEPT RESULT

    function acceptResult(~,~)

        if isempty(fieldnames(currentResult))

            uialert(fig, ...
                "Analyze an image before accepting the result.", ...
                "NetraScreen");

            return;

        end

        reviewStatus = "Accepted";

        reviewLabel.Text = ...
            "Review status: ACCEPTED";

        statusLabel.Text = ...
            "AI result accepted by human reviewer.";

    end

%% OVERRIDE RESULT

    function overrideResult(~,~)

        if isempty(fieldnames(currentResult))

            uialert(fig, ...
                "Analyze an image before overriding the result.", ...
                "NetraScreen");

            return;

        end

        options = { ...
            "No DR", ...
            "Mild NPDR", ...
            "Moderate NPDR", ...
            "Severe NPDR", ...
            "Proliferative DR"};

        [selection,ok] = listdlg( ...
            "PromptString","Select human-reviewed diagnosis:", ...
            "SelectionMode","single", ...
            "ListString",options, ...
            "ListSize",[300 160]);

        if ~ok
            return;
        end

        humanGrade = selection - 1;

        currentResult.humanGrade = humanGrade;

        currentResult.humanDiagnosis = ...
            options{selection};

        reviewStatus = "Overridden";

        reviewLabel.Text = ...
            "Review status: OVERRIDDEN";

        statusLabel.Text = ...
            "Human reviewer selected: " + ...
            options{selection};

    end

%% SAVE REVIEW

    function saveReview(~,~)

        if isempty(fieldnames(currentResult))

            uialert(fig, ...
                "No analysis available to save.", ...
                "NetraScreen");

            return;

        end

        currentResult.reviewStatus = reviewStatus;

        currentResult.reviewTime = datetime("now");

        if ~exist("outputs/reviews","dir")
            mkdir("outputs/reviews");
        end

        timestamp = datestr(now,"yyyymmdd_HHMMSS");

        filename = fullfile( ...
            "outputs","reviews", ...
            "NetraScreen_Review_" + timestamp + ".mat");

        result = currentResult; %#ok<NASGU>

        save(filename,"result");

        statusLabel.Text = ...
            "Review saved successfully.";

        uialert(fig, ...
            "Review saved successfully.", ...
            "NetraScreen");

    end

